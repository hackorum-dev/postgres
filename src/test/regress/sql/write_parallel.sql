--
-- PARALLEL
--

begin;

-- encourage use of parallel plans
set parallel_setup_cost=0;
set parallel_tuple_cost=0;
set min_parallel_table_scan_size=0;
set max_parallel_workers_per_gather=4;

--
-- Test write operations that has an underlying query that is eligible
-- for parallel plans
--
explain (costs off) create table parallel_write as
    select length(stringu1) from tenk1 group by length(stringu1);
create table parallel_write as
    select length(stringu1) from tenk1 group by length(stringu1);
drop table parallel_write;

explain (costs off) select length(stringu1) into parallel_write
    from tenk1 group by length(stringu1);
select length(stringu1) into parallel_write
    from tenk1 group by length(stringu1);
drop table parallel_write;

explain (costs off) create materialized view parallel_mat_view as
    select length(stringu1) from tenk1 group by length(stringu1);
create materialized view parallel_mat_view as
    select length(stringu1) from tenk1 group by length(stringu1);
create unique index on parallel_mat_view(length);
refresh materialized view parallel_mat_view;
refresh materialized view concurrently parallel_mat_view;
drop materialized view parallel_mat_view;

prepare prep_stmt as select length(stringu1) from tenk1 group by length(stringu1);
explain (costs off) create table parallel_write as execute prep_stmt;
create table parallel_write as execute prep_stmt;
drop table parallel_write;

create table parallel_source with (parallel_workers = 2) as
  select i from generate_series(1, 10000) g(i);
analyze parallel_source;
create table parallel_write (i int primary key, s int generated by default as identity);

-- Only buffer an INSERT source if the option is on and the plan is parallel.
explain (costs off) insert into parallel_write (i, s) select i, i from parallel_source;
set enable_insert_select_parallel = on;
explain (costs off) insert into parallel_write (i, s) select i, i from parallel_source;
explain (costs off) insert into parallel_write (i) select 42;

-- Force the buffer to spill, and check that all the rows survive.
set work_mem = '64kB';
do $$
declare
  p json;
begin
  execute 'explain (analyze, format json)
           insert into parallel_write (i, s) select i, i from parallel_source' into p;
  raise notice 'TupleBuffer storage: %, workers launched: %',
    p #>> '{0,Plan,Plans,0,Storage}', p #>> '{0,Plan,Plans,0,Plans,0,Workers Launched}';
end $$;
select count(*), sum(i) from parallel_write;

-- LIMIT can leave Gather Merge workers active.  Shut them down before
-- evaluating the identity default and performing the conflict updates.
explain (costs off)
insert into parallel_write (i) select i from parallel_source order by i desc limit 2
  on conflict (i) do update set s = excluded.s returning i, s;
insert into parallel_write (i) select i from parallel_source order by i desc limit 2
  on conflict (i) do update set s = excluded.s returning i, s;

-- A parallel initplan of the SELECT also requires a buffer.  Its LIMIT
-- leaves workers to be shut down before evaluating the identity default.
explain (costs off)
insert into parallel_write (i)
  select (select i + 1 from parallel_source order by i desc limit 1);
insert into parallel_write (i)
  select (select i + 1 from parallel_source order by i desc limit 1) returning i, s;

-- A failure on the second source row must not consume an identity value for
-- the first.  Sequence advances, unlike inserted rows, survive rollback.
savepoint before_error;
insert into parallel_write (i)
  select (select max(i) + 2 from parallel_source) / n from (values (1), (0)) v(n);
rollback to before_error;
select currval(pg_get_serial_sequence('parallel_write', 's'));

-- A row-locking source or a data-modifying CTE still rules out parallelism.
explain (costs off)
insert into parallel_write (i) select i from parallel_source for update;
explain (costs off)
with d as (delete from parallel_write returning i)
insert into parallel_write (i) select i from parallel_source;

-- setrefs discards a parallel hashed SubPlan in favor of a serial index
-- probe.  The TupleBuffer remains, but must pass the first row through
-- before the second row raises an error.
create unique index on parallel_source(i);
create temp table parallel_outer as select i from (values (1), (2)) v(i);
analyze parallel_outer;
reset work_mem;
explain (costs off)
insert into parallel_write (i)
  select 20000 + exists (select from parallel_source s where s.i = o.i)::int
                 / (2 - row_number() over ())::int
  from parallel_outer o;
savepoint before_passthrough_error;
insert into parallel_write (i)
  select 20000 + exists (select from parallel_source s where s.i = o.i)::int
                 / (2 - row_number() over ())::int
  from parallel_outer o;
rollback to before_passthrough_error;
select currval(pg_get_serial_sequence('parallel_write', 's'));

-- With more outer rows, the parallel hashed SubPlan wins and needs buffering
-- even though the outer scan is serial.
insert into parallel_outer select generate_series(3, 1000);
analyze parallel_outer;
explain (costs off)
insert into parallel_write (i, s)
  select o.i + 20000, exists (select from parallel_source s where s.i = o.i)::int
  from parallel_outer o;

rollback;
